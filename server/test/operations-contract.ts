import assert from 'node:assert/strict';
import type {FastifyInstance,InjectOptions} from 'fastify';
import type {GameStore} from '../src/contract.js';
import {makePasswordHash} from '../src/operations.js';
export const fixturePassword = 'disposable-owner-test-password';
export const fixtureOwner = {username: 'test_owner', passwordHash: makePasswordHash(fixturePassword), origin: 'https://street.test', secure: true};
export async function operationsContract(store: GameStore, app: FastifyInstance) {
  const inject = (options: string | InjectOptions) => app.inject(typeof options === 'string' ? {url:options,remoteAddress:'127.0.0.8'} : {...options,remoteAddress:'127.0.0.8'});
  const origin = fixtureOwner.origin;
  assert.equal((await inject('/api/owner/overview')).statusCode, 401);
  assert.equal((await inject({method:'POST',url:'/api/owner/login',payload:{username:fixtureOwner.username,password:fixturePassword}})).statusCode,403);
  assert.equal((await inject({method:'POST',url:'/api/owner/login',headers:{origin},payload:{username:fixtureOwner.username,password:'incorrect'}})).statusCode,401);
  const login=await inject({method:'POST',url:'/api/owner/login',headers:{origin},payload:{username:fixtureOwner.username,password:fixturePassword}});
  assert.equal(login.statusCode,200);
  const cookie=String(login.headers['set-cookie']).split(';')[0];
  assert.ok(String(login.headers['set-cookie']).includes('HttpOnly') && String(login.headers['set-cookie']).includes('Secure') && String(login.headers['set-cookie']).includes('SameSite=Strict'));
  const headers={cookie,origin,'x-csrf-token':login.json().csrfToken};
  assert.equal((await inject({url:'/api/owner/session',headers:{cookie}})).statusCode,200);
  const guest=(await inject({method:'POST',url:'/api/v1/guests',payload:{}})).json();
  const auth={authorization:`Bearer ${guest.token}`};
  const profile=await inject({url:'/api/owner/players/'+guest.character.id,headers});
  assert.equal(profile.statusCode,200);assert.ok(!profile.body.includes(guest.token) && !profile.body.includes(guest.recoveryCode) && !profile.body.includes('save_key_hash'));
  assert.equal((await inject({url:'/api/owner/overview',headers:auth})).statusCode,401);
  const settings={...(await store.ops.settings()),announcement:'The square is open for everyone.',newCharacterSeed:991337,maintenance:true,favorEnabled:false,amakaLine:'Welcome to our street, neighbor.'};
  const publish=(h:Record<string,string>,value=settings)=>app.inject({method:'PUT',url:'/api/owner/settings',headers:h,payload:{settings:value,reason:'Testing scheduled neighborhood maintenance'}});
  assert.equal((await publish({cookie,origin})).statusCode,403);
  assert.equal((await publish({...headers,'x-csrf-token':'é'.repeat(43)})).statusCode,403);
  assert.equal((await publish({...headers,origin:'https://other.test'})).statusCode,403);
  assert.equal((await publish(headers,{...settings,newCharacterSeed:-1})).statusCode,400);
  assert.equal((await publish(headers)).statusCode,200);
  assert.equal((await publish(headers)).statusCode,409);
  assert.equal((await store.read(guest.character.id)).state.world_seed,260713);
  const future=(await inject({method:'POST',url:'/api/v1/guests',payload:{}})).json();
  assert.equal(future.character.state.world_seed,991337);
  const intent=(kind:string,choice?:string)=>app.inject({method:'POST',url:'/api/v1/intents',headers:{...auth,'idempotency-key':'operations-intent-test'},payload:{kind,choice,revision:0}});
  assert.equal((await intent('greet')).statusCode,423);
  assert.equal((await intent('sync')).statusCode,200);
  let current=await store.ops.settings();
  await store.ops.updateSettings(current.revision,{...current,maintenance:false},'test_owner','Resume activities for test');
  const command=(key:string,revision:number,kind:string,choice?:string)=>app.inject({method:'POST',url:'/api/v1/intents',headers:{...auth,'idempotency-key':key},payload:{revision,kind,choice}});
  await command('operations-greet-001',1,'greet');
  assert.equal((await command('operations-accept-01',2,'neighbor','favor_accept')).statusCode,422);
  current=await store.ops.settings();await store.ops.updateSettings(current.revision,{...current,favorEnabled:true},'test_owner','Reopen the favor for testing');
  assert.equal((await command('operations-accept-01',2,'neighbor','favor_accept')).statusCode,200);
  current=await store.ops.settings();await store.ops.updateSettings(current.revision,{...current,favorEnabled:false},'test_owner','Pause only new favors');
  assert.equal((await command('operations-deliver-1',3,'neighbor','favor_deliver')).statusCode,200);
  assert.equal((await command('operations-complete',4,'neighbor','favor_finish')).statusCode,200);
  const access=(action:string)=>app.inject({method:'POST',url:'/api/owner/players/'+guest.character.id+'/access',headers,payload:{action,reason:'Support test with retained progress'}});
  assert.equal((await access('suspend')).statusCode,200);
  assert.equal((await inject({url:'/api/v1/me',headers:auth})).statusCode,403);
  assert.equal((await inject({method:'POST',url:'/api/v1/sessions',payload:{recoveryCode:guest.recoveryCode}})).statusCode,403);
  assert.equal((await access('resume')).statusCode,200);
  const other=(await inject({method:'POST',url:'/api/v1/sessions',payload:{recoveryCode:guest.recoveryCode}})).json();
  const rotated=await inject({method:'POST',url:'/api/v1/save-code',headers:auth,payload:{revision:5}});
  assert.equal(rotated.statusCode,200);assert.ok(rotated.json().recoveryCode.length>=40);
  assert.equal((await inject({url:'/api/v1/me',headers:{authorization:`Bearer ${other.token}`}})).statusCode,401);
  assert.equal((await inject({url:'/api/v1/me',headers:auth})).statusCode,200);
  assert.equal((await inject({method:'POST',url:'/api/v1/sessions',payload:{recoveryCode:guest.recoveryCode}})).statusCode,401);
  assert.equal((await inject({method:'POST',url:'/api/v1/sessions',payload:{recoveryCode:rotated.json().recoveryCode}})).statusCode,200);
  assert.equal((await store.read(guest.character.id)).state.coins,270);
  assert.equal((await access('revoke_sessions')).statusCode,200);
  assert.equal((await inject({url:'/api/v1/me',headers:auth})).statusCode,401);
  const audit=(await inject({url:'/api/owner/audit',headers})).json();
  assert.ok(audit.events.some((event:any)=>event.action==='save_code.rotate'));
  assert.ok(audit.events.some((event:any)=>event.action==='player.suspend'));
  assert.ok(!JSON.stringify(audit).includes(rotated.json().recoveryCode));
  assert.equal((await inject({url:'/api/owner/audit?before='+audit.events[0].id,headers})).statusCode,200);
  assert.equal((await inject({method:'POST',url:'/api/owner/logout',headers,payload:{}})).statusCode,200);
  assert.equal((await inject({url:'/api/owner/session',headers:{cookie}})).statusCode,401);
  current=await store.ops.settings();await store.ops.updateSettings(current.revision,{...current,favorEnabled:true,maintenance:false,newCharacterSeed:260713},'test_owner','Restore default settings after contract test');
  return guest.character.id as string;
}
